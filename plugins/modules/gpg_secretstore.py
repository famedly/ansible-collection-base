class UserSuppliedSecretMissingError(Exception):
    pass


class SecretGenerator:
    ALLOWED_SECRET_TYPES = ["random", "binary", "user_supplied"]

    def __init__(self, secret_type: str = "random", data_type: str = "plain", **kwargs):
        self.secret_type = secret_type.lower()
        self.data_type = data_type.lower()
        self.kwargs = kwargs
        if self.secret_type not in self.ALLOWED_SECRET_TYPES:
            raise NotImplementedError(f"Secret type {secret_type} is not supported")

    def getSecret(self):
        if self.secret_type == "random":
            return self.__randomSecret(**self.kwargs)
        if self.secret_type == "binary":
            return self.__binarySecret(**self.kwargs)
        if self.secret_type == "user_supplied":
            return self.__userSuppliedSecret(**self.kwargs)
        raise NotImplementedError(f"Secret type {self.secret_type} is not supported")

    def getSecretData(self):
        if self.data_type == "plain":
            return self.getSecret()
        if self.data_type == "json":
            return json.loads(self.getSecret())
        if self.data_type == "yaml":
            return yaml.safe_load(self.getSecret())
        raise NotImplementedError(f"Data type {self.data_type} is not supported")

    @staticmethod
    def __randomSecret(
        length: int = 30, letter_pattern: str = "([A-Za-z0-9])", **kwargs
    ):
        import secrets
        import re
        import string

        characters = re.findall(letter_pattern, string.printable)
        return "".join(secrets.choice(characters) for i in range(length))

    @staticmethod
    def __binarySecret(binary: str, **kwargs):
        import subprocess

        binary = binary.split()
        process = subprocess.run(binary, capture_output=True, check=True)
        return process.stdout.decode("UTF-8")

    @staticmethod
    def __userSuppliedSecret(user_supplied_secret: str, **kwargs):
        if user_supplied_secret is None:
            raise UserSuppliedSecretMissingError(
                "User supplied secret configured, but it's neither in the store nor supplied"
            )
        return user_supplied_secret


# Options describing a single secret. In batch mode (`secrets`), the top-level
# values act as defaults for every entry.
SECRET_OPTIONS = dict(
    state=dict(type="str", choices=["present", "absent"], default="present"),
    data_type=dict(type="str", choices=["plain", "yaml", "json"], default="plain"),
    secret_fact=dict(type="str", no_log=False),
    overwrite=dict(type="bool", default=False),
    secret_type=dict(
        type="str",
        choices=["random", "binary", "user_supplied"],
        default="random",
        no_log=False,
    ),
    secret_binary=dict(type="str", no_log=False),
    secret_length=dict(type="int", default=20, no_log=False),
    secret_pattern=dict(type="str", default="([A-Za-z0-9])", no_log=False),
    user_supplied_secret=dict(type="str", no_log=True),
    skip_missing=dict(type="bool", default=False),
)


def main():
    secret_suboptions = {
        name: {key: value for key, value in spec.items() if key != "default"}
        for name, spec in SECRET_OPTIONS.items()
    }
    secret_suboptions["password_slug"] = dict(required=True, type="str", no_log=False)

    module = AnsibleModule(
        argument_spec=dict(
            # General arguments
            password_store_path=dict(
                required=False, type="str", default="~/.password-store/", no_log=False
            ),
            file_extension=dict(required=False, type="str", default=".gpg"),
            keyring=dict(
                required=False, type="str", default="pubring.kbx", no_log=False
            ),
            pass_gpg_id_file=dict(
                required=False, type="str", default=".gpg-id", no_log=False
            ),
            password_slug=dict(required=False, type="str", no_log=False),
            secrets=dict(
                required=False,
                type="list",
                elements="dict",
                options=secret_suboptions,
                no_log=False,
            ),
            session_key_cache_socket=dict(required=False, type="str", no_log=False),
            **SECRET_OPTIONS,
        ),
        required_one_of=[("password_slug", "secrets")],
        mutually_exclusive=[("password_slug", "secrets")],
        supports_check_mode=True,
    )

    errors = []
    traceback = []
    warnings = []

    # Warn if running as root
    if os.geteuid() == 0:
        warnings.append("Running as root, ensure GPG keyring is present for root user")

    error_map = check_secretstore_import_errors() | check_module_import_errors()
    for lib, exception in error_map.items():
        warnings.append(f"Missing python library: {lib}")
        errors.append(missing_required_lib(lib))
        traceback.append(str(exception))
    if errors:
        module.fail_json(
            warning=",\n".join(warnings),
            errors=errors,
            traceback="\n".join(traceback),
            msg=",\n".join(warnings),
        )

    store = SecretStore(
        password_store_path=module.params["password_store_path"],
        file_extension=module.params["file_extension"],
        keyring=module.params["keyring"],
        pass_gpg_id_file=module.params["pass_gpg_id_file"],
        session_key_cache_socket=module.params["session_key_cache_socket"],
    )

    if module.params["secrets"] is None:
        result = _process_secret(module, store, module.params)
        result["warning"] = warnings + result["warning"]
        for warn_msg in result["warning"]:
            module.warn(warn_msg)
        if result["failed"]:
            module.fail_json(**result)
        module.exit_json(**result)

    # Batch mode: process all secrets in a single module run
    results = []
    for secret in module.params["secrets"]:
        params = {
            name: module.params[name] if secret[name] is None else secret[name]
            for name in SECRET_OPTIONS
        }
        params["password_slug"] = secret["password_slug"]
        result = _process_secret(module, store, params)
        for warn_msg in result["warning"]:
            module.warn(f"{params['password_slug']}: {warn_msg}")
        results.append(result)

    for warn_msg in warnings:
        module.warn(warn_msg)
    batch_result = dict(
        changed=any(result["changed"] for result in results),
        results=results,
        ansible_facts={
            name: value
            for result in results
            for name, value in result.pop("ansible_facts").items()
        },
        diff=[result.pop("diff") for result in results],
        warning=warnings,
    )
    failed_slugs = [result["password_slug"] for result in results if result["failed"]]
    if failed_slugs:
        module.fail_json(
            msg="Failed to process secret(s): " + ", ".join(failed_slugs),
            **batch_result,
        )
    module.exit_json(**batch_result)


def _process_secret(module, store, params):
    """Ensure the state of a single secret and return its result"""
    password_slug = params["password_slug"]
    result = dict(
        changed=False,
        failed=False,
        message="",
        warning=[],
        password_slug=password_slug,
        secret="",
        ansible_facts={},
        diff={
            "before_header": f"{password_slug} gpg recipients",
            "after_header": f"{password_slug} gpg recipients",
            "before": [],
            "after": [],
        },
    )

    try:
        _ensure_secret(module, store, params, result)
    except UserSuppliedSecretMissingError as e:
        result["msg"] = str(e)
        result["changed"] = False
        result["failed"] = True

    if result["message"]:
        module.log(result["message"])

    result["diff"]["before"] = "\n".join(result["diff"]["before"]) + "\n"
    result["diff"]["after"] = "\n".join(result["diff"]["after"]) + "\n"

    return result


def _ensure_secret(module, store, params, result):
    secretGenerator = SecretGenerator(
        secret_type=params["secret_type"],
        data_type=params["data_type"],
        binary=params["secret_binary"],
        length=params["secret_length"],
        letter_pattern=params["secret_pattern"],
        user_supplied_secret=params["user_supplied_secret"],
    )

    state = params["state"]
    password_slug = params["password_slug"]
    data_type = params["data_type"]
    overwrite = params["overwrite"]

    lock = FileLock(
        (Path("/tmp/") / hashlib.md5(password_slug.encode()).hexdigest()).as_posix()
    )
    with lock:
        if state == "present":
            try:
                result["diff"]["before"] = store.get_recipients_from_encrypted_file(
                    slug=password_slug
                )
                if not overwrite:
                    result["secret"] = store.get(
                        slug=password_slug, data_type=data_type
                    )
                    result["changed"] = False
                else:
                    result["message"] = (
                        "Secret rotation requested: rotating, if possible."
                    )
                    result["secret"] = secretGenerator.getSecretData()
                    result["action"] = "update"
                    result["changed"] = True
                result["diff"]["after"] = result["diff"]["before"]

            except FileNotFoundError:
                if params["skip_missing"]:
                    result["message"] = "Secret not found, skipping generation"
                    del result["secret"]
                else:
                    result["message"] = "Secret not found! Generation new secret"
                    result["secret"] = secretGenerator.getSecretData()
                    result["diff"]["before"] = []
                    result["diff"]["after"] = store.get_recipients(
                        slug=password_slug
                    )
                    result["action"] = "add"
                    result["changed"] = True

            except RecipientsMismatchError:
                result["warning"].append("Secret-Recipient-Mismatch! Re-encrypting.")
                result["secret"] = store.get(
                    slug=password_slug, data_type=data_type, check_recipients=False
                )
                result["diff"]["before"] = store.get_recipients_from_encrypted_file(
                    slug=password_slug
                )
                result["diff"]["after"] = store.get_recipients(slug=password_slug)
                result["action"] = "update"
                result["changed"] = True

            except GPGException as e:
                result["msg"] = "GPG Exception: " + str(e)
                result["failed"] = True

            if params["secret_fact"] and "secret" in result:
                result["ansible_facts"][params["secret_fact"]] = result["secret"]

            if result["changed"] and not module.check_mode:
                store.put(
                    slug=password_slug, data=result["secret"], data_type=data_type
                )
                _commit_changes(
                    module.params["password_store_path"],
                    password_slug + module.params["file_extension"],
                )
                result["diff"]["after"] = store.get_recipients_from_encrypted_file(
                    slug=password_slug
                )

        if state == "absent":
            try:
                result["diff"]["before"] = store.get_recipients_from_encrypted_file(
                    slug=password_slug
                )
                if module.check_mode:
                    store.get(slug=password_slug, data_type=data_type)
                else:
                    store.remove(slug=password_slug)
                    _commit_changes(
                        module.params["password_store_path"],
                        password_slug + module.params["file_extension"],
                        True,
                    )
                result["message"] = "Secret will be deleted!"
                result["diff"]["after"] = []
                result["action"] = "remove"
                result["changed"] = True
            except FileNotFoundError:
                result["message"] = "Secret didn't exist"
                result["diff"]["before"] = []
                result["diff"]["after"] = []
                result["changed"] = False


def _commit_changes(repo_path: str, file_path: str, remove: bool = False):
    lock = FileLock(
        (Path("/tmp/") / hashlib.md5(repo_path.encode()).hexdigest()).as_posix()
    )
    with lock:
        repo = Repo(repo_path)
        if remove:
            message = f"Remove secret {file_path}"
            repo.index.remove(file_path)
        else:
            try:
                repo.tree() / file_path
                message = f"Update secret {file_path}"
            except KeyError:
                message = f"Add secret {file_path}"
            repo.index.add(file_path)
        repo.index.write()
        # Using the direct git call as signed commits are not possible using git plumbing
        repo.git.commit("-m", message)


